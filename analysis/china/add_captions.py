# The plotly subtitle marker used by analysis/china/common.py:save_multi_plotly_html
SUBTITLE_RE = re.compile(r'(<h3 style="color:#E6EDF3;margin:24px 0 6px 0">[^<]+</h3>)')
# Footer closing (marks end of all chart content)
FOOTER_RE = re.compile(r'(<div class="step-footer">)')
# Pyvis / network container marker
PYVIS_CARD_RE = re.compile(
    r'(<div style="background:#161B22;border:1px solid #30363D;border-radius:8px;">.*?</div>)',
    re.DOTALL,
)
# Already-injected sentinel
CAPTION_SENTINEL = 'class="chart-caption"'


def _caption_div(html: str) -> str:
    return f'<div class="chart-caption">{html}</div>'


def inject_multi_plotly(html: str, captions: list[str]) -> str:
    """Inject a caption after each plotly chart in a multi-plotly HTML.

    Strategy: split the body on <h3 subtitle> markers — each section that
    starts with a subtitle ends either at the next subtitle or at the step
    footer. We append a caption just before the next boundary.
    """
    # Find all subtitle positions
    matches = list(SUBTITLE_RE.finditer(html))
    footer_m = FOOTER_RE.search(html)
    if not matches:
        # no subtitles at all — should not happen for multi-plotly; fall back
        return html

    # Build list of section boundaries: (subtitle_start, section_end_before_next_subtitle_or_footer)
    boundaries = []
    for i, m in enumerate(matches):
        sec_start = m.start()
        if i + 1 < len(matches):
            sec_end = matches[i + 1].start()
        elif footer_m:
            sec_end = footer_m.start()
        else:
            sec_end = len(html)
        boundaries.append((sec_start, sec_end))

    # Inject captions from last to first (so indices stay valid)
    out = html
    for i in range(len(boundaries) - 1, -1, -1):
        if i >= len(captions):
            continue
        _, sec_end = boundaries[i]
        cap = _caption_div(captions[i])
        out = out[:sec_end] + cap + out[sec_end:]
    return out


def inject_pyvis_or_single(html: str, captions: list[str]) -> str:
    """For pyvis / single-chart HTMLs: inject caption right before the footer."""
    if not captions:
        return html
    footer_m = FOOTER_RE.search(html)
    if not footer_m:
        return html
    cap = _caption_div(captions[0])
    return html[:footer_m.start()] + cap + html[footer_m.start():]


def inject_css(html: str) -> str:
    """Add caption CSS inside <head>, right before </head>."""
    if '.chart-caption' in html:
        return html
    return html.replace('</head>', CAPTION_CSS + '</head>', 1)


